"""Writes generated/models.py from schema/models.json (`--out PATH` writes somewhere else)."""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ROUNDING = {"floor": "(gross * (100 - self.discount_pct)) // 100", "half_up": "(gross * (100 - self.discount_pct) + 50) // 100"}


def render(schema):
    out = ["# generated by tools/gen.py from schema/models.json", ""]
    for name, spec in schema.items():
        out += ["", "class %s:" % name, "    def __init__(self, lines, discount_pct=0):", "        self.lines = lines", "        self.discount_pct = discount_pct", "",
                "    def total(self):", "        gross = sum(self.lines)", "        return " + ROUNDING[spec["rounding"]], ""]
    return "\n".join(out)


if __name__ == "__main__":
    target = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else os.path.join(ROOT, "generated", "models.py")
    with open(os.path.join(ROOT, "schema", "models.json")) as f:
        text = render(json.load(f))
    with open(target, "w") as f:
        f.write(text)
